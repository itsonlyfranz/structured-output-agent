"""Regenerate the README agent-flow diagram from the compiled LangGraph graph.

    python scripts/render_graph.py           # rewrite the diagram block in README.md
    python scripts/render_graph.py --check   # exit 1 if the README is out of date

Fully offline: the graph is compiled with a stub client and never invoked.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START_MARK = "<!-- flow-diagram:start (generated by scripts/render_graph.py) -->"
END_MARK = "<!-- flow-diagram:end -->"
BLOCK = re.compile(re.escape(START_MARK) + r".*?" + re.escape(END_MARK), re.DOTALL)


def drawable_graph():
    """The tool-using graph (the superset of the runner's graph), compiled but never run."""
    sys.path.insert(0, str(ROOT / "src"))
    from structured_output_agent.failures import ValidationFailureLog
    from structured_output_agent.graph import ActResult, build_graph

    graph = build_graph(
        client=None,  # type: ignore[arg-type]  # compiled only, never run
        system="",
        schema="",
        run_id="render",
        validate=lambda raw: (True, raw, raw),
        failure_log=ValidationFailureLog(),
        max_retries=3,
        act=lambda value: ActResult(tool="", observation=""),
        max_steps=1,
    )
    return graph.get_graph()


def flow_mermaid() -> str:
    return drawable_graph().draw_mermaid().strip()


def render_block() -> str:
    return f"{START_MARK}\n```mermaid\n{flow_mermaid()}\n```\n{END_MARK}"


def updated_readme(text: str) -> str:
    if not BLOCK.search(text):
        raise SystemExit(f"{README.name}: flow-diagram markers not found")
    return BLOCK.sub(lambda _: render_block(), text, count=1)


def main(argv: list[str]) -> int:
    text = README.read_text()
    new = updated_readme(text)
    if "--check" in argv:
        if new != text:
            print("README flow diagram is stale; run python scripts/render_graph.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
